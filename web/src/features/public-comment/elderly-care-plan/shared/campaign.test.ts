import { describe, expect, it } from "vitest";
import { ELDERLY_CARE_PLAN_QUESTIONS } from "./campaign";

describe("第10期高齢・介護計画AIインタビューの固定質問", () => {
  it("指定された7段階の見出しと固定質問を順番どおり保持する", () => {
    expect(ELDERLY_CARE_PLAN_QUESTIONS).toHaveLength(7);
    expect(
      ELDERLY_CARE_PLAN_QUESTIONS.map((question) => question.topic)
    ).toEqual([
      "この計画と、あなたの暮らしとの関わり",
      "計画の中で、特に考えたいこと",
      "経験や不安から、具体的な課題を見つける",
      "区の目的や取組について、納得できる点・まだ分からない点",
      "支援が暮らしに役立っていることを、どう確かめるか",
      "計画や実施方法を、具体的にどうしてほしいか",
      "区に最も伝えたいことを、一文にまとめる",
    ]);
    expect(
      ELDERLY_CARE_PLAN_QUESTIONS.map((question) => question.question)
    ).toEqual([
      "今回の計画は、2027～2029年度の世田谷区の高齢者支援と介護保険の運営方針を定めるものです。\n\nあなたは、ご自身の高齢期の暮らし、家族などの介護、地域での支えあい、医療・介護の仕事など、どのような立場や関心から意見を伝えたいですか？\n\n今は介護に関わっていなくても、将来への不安や期待からお話しいただいて構いません。この対話では、個人名や詳しい病状を話す必要はありません。",
      "素案では、健康づくり・介護予防、外出や地域活動・就労、相談や在宅生活の支援、認知症への対応、介護人材の確保、介護サービスや保険料などを扱っています。\n\nこの中で、あなたが特に大切だと思うことや、詳しく考えたいことはどれですか？\n\n『介護をする家族の生活』『一人暮らしでも頼れる支援』『働き続けられる介護の職場』など、ご自身の言葉で挙げていただいて構いません。ここにない論点でも大丈夫です。",
      "いま挙げていただいた点について、これまでに助けになった支援や、反対に、相談・サービスの利用・地域活動への参加を難しくしたことはありますか？\n\n例えば、情報の見つけやすさ、窓口の対応、費用、移動手段、利用できる時間帯など、どのようなことが関わっていたでしょうか。ご本人や家族の暮らし、仕事、安心感への影響も、話せる範囲で教えてください。経験がなければ、今後への不安や希望でも構いません。",
      "区は、健康づくりと介護予防、外出・地域活動や就労の促進、介護人材の確保と事業所の安定経営への支援を、今回の計画の重点にしています。\n\nあなたが挙げた経験や関心から見ると、こうした計画の目的や具体的な取組について、納得できる点と、まだ不十分だと感じる点はありますか？ 『方向性には納得できるが、実施方法が分からない』など、説明を補ってほしい点や、判断がつかない点でも構いません。",
      "素案では、地域活動への参加状況、区の支援を通じて採用につながった介護職員数、介護事業者の経営状況などを、取組を評価する指標として挙げています。\n\nあなたが気にしている点について、どのような状態になれば『必要な支援が届き、暮らしに役立っている』と判断できますか？\n\n例えば、希望する活動に参加できること、必要なときに介護サービスを利用できること、介護する家族が休息を取れることなどです。その状態を区が確かめるには、どのような情報を調べたり、誰の声を聴いたりするとよいと思いますか？",
      "今回の公開素案には、介護サービスの見込量や第10期の保険料など、今後具体化される部分もあります。\n\nここまでの話を踏まえて、計画への追記・修正や、実際の支援の進め方について、区に何を求めたいですか？\n\n『誰に対して、どの支援や説明を、どのようにしてほしいか』を、分かる範囲で教えてください。制度の詳しい設計まで考える必要はありません。変更ではなく、今ある取組を続けてほしいという意見でも構いません。",
      "ここまでお話しいただいた中で、今回の高齢者支援・介護保険の計画に、最も反映してほしいことは何ですか？\n\n『誰が、どのように暮らせるように、区に何をしてほしいか』を手がかりに、区へ伝える一文にすると、どのような言葉になりますか？",
    ]);
  });

  it("立場を限定せずに選べる最初の回答候補を用意する", () => {
    expect(ELDERLY_CARE_PLAN_QUESTIONS[0].quickReplies).toEqual([
      "自分の高齢期の暮らしから",
      "家族などの介護から",
      "地域での支えあいから",
      "医療・介護の仕事や制度への関心から",
    ]);
  });
});
