import { describe, expect, it } from "vitest";
import { TRAFFIC_SAFETY_PLAN_QUESTIONS } from "./campaign";

describe("第12次交通安全計画AIインタビューの固定質問", () => {
  it("指定された7段階の見出しと固定質問を順番どおり保持する", () => {
    expect(TRAFFIC_SAFETY_PLAN_QUESTIONS).toHaveLength(7);
    expect(
      TRAFFIC_SAFETY_PLAN_QUESTIONS.map((question) => question.topic)
    ).toEqual([
      "普段の移動と、この計画との関わり",
      "今回の計画で、特に考えたいこと",
      "日常の経験から、何を変えてほしいか",
      "区が掲げる目標や対策に、納得できるか",
      "対策が進み、安全になったことをどう確かめるか",
      "計画や実施方法に、具体的に何を求めるか",
      "区に最も伝えたいことをまとめる",
    ]);
    expect(
      TRAFFIC_SAFETY_PLAN_QUESTIONS.map((question) => question.question)
    ).toEqual([
      "世田谷区内で、普段どのように移動していますか。徒歩、自転車、車やバイク、子どもの送迎、車いすでの移動、仕事での運転など、今回の交通安全計画について意見を伝えたい立場や、日常の移動場面を教えてください。複数の立場でも構いません。この対話では、住所や氏名など、個人を特定できる情報は不要です。",
      "素案では、高齢者や子どもの安全、自転車・バイクの事故防止、飲酒運転対策、電動キックボードなどの小型モビリティへの対応を重点課題にしています。道路環境の整備や、事故に遭った人への支援も含まれています。あなたが特に大切だと思うこと、気になっていることはどれですか。『通学路の安全』『自転車が走る場所』『歩行者との接触』『交通ルールの周知』など、身近な場面から挙げても構いません。",
      "いま挙げていただいた点について、どのような場所や状況で、危険や不便を感じましたか。反対に、安全対策が役立っていると感じた経験はありますか。例えば、交差点を渡るとき、歩道のない道を通るとき、自転車や車の通行・駐停車がある場面など、話せる範囲で教えてください。事故の体験を詳しく話す必要はなく、『こうなれば安心して移動できる』という期待だけでも構いません。",
      "素案は、2030年度までに交通事故の死者数０人、負傷者数1,650人以下を目指しています。そのために、安全教育やルールの周知、道路・通行空間の整備、指導・取締りなどを組み合わせる方針です。この目標や、あなたが関心を持つ分野の対策について、納得できる点と、まだ不十分だと思う点はありますか。判断するために、もう少し説明してほしいことがあれば、それも教えてください。",
      "この計画では、区や警察、学校、事業者などが連携して対策を進めます。あなたが関心を持つ対策について、実際に取り組まれているか、安全につながっているかを確かめるには、どのような情報や確認の仕組みが必要だと思いますか。例えば、危険箇所への対応状況、担当機関と実施時期、事故やけがの状況の変化、道路を使う人の声など、何を確認できるとよいでしょうか。",
      "ここまでのお話を踏まえて、この交通安全計画の記述や、実際の対策の進め方について、区にどのような修正・追加・運用改善を求めたいですか。対象にする道路や利用者、対策の内容、取り組む順番や時期、周知・相談の方法など、具体化できる範囲で教えてください。変更を求めることだけでなく、今の内容で続けてほしい取組や、区から説明してほしい点でも構いません。",
      "ここまでの内容のうち、第12次世田谷区交通安全計画に関して、区に最も伝えたいことを一言で表すと何ですか。『誰が、どのような場面で、安心して移動できるようになってほしいか』や『そのために区に何をしてほしいか』を手がかりに、あなたの言葉で教えてください。",
    ]);
  });

  it("複数の移動手段・立場を選べる最初の回答候補を用意する", () => {
    expect(TRAFFIC_SAFETY_PLAN_QUESTIONS[0].quickReplies).toEqual([
      "徒歩や車いすで移動する立場から",
      "自転車で移動する立場から",
      "車・バイク・仕事で運転する立場から",
      "子どもの送迎や見守りの立場から",
    ]);
  });
});
