import { describe, expect, it } from "vitest";
import { DEMENTIA_HOPE_PLAN_QUESTIONS } from "./campaign";

describe("第3期認知症希望計画AIインタビューの固定質問", () => {
  it("指定された7段階の見出しと固定質問を順番どおり保持する", () => {
    expect(DEMENTIA_HOPE_PLAN_QUESTIONS).toHaveLength(7);
    expect(
      DEMENTIA_HOPE_PLAN_QUESTIONS.map((question) => question.topic)
    ).toEqual([
      "この計画との関わり",
      "特に考えたい論点",
      "経験や不安から、暮らしの中の課題を確かめる",
      "計画の目的や進め方について、納得できる点と不十分な点を考える",
      "取組が暮らしに役立っているか、何で確かめるか",
      "区に求める修正や、支援の進め方を具体化する",
      "区に最も伝えたいことをまとめる",
    ]);
    expect(
      DEMENTIA_HOPE_PLAN_QUESTIONS.map((question) => question.question)
    ).toEqual([
      "この計画は、認知症の本人の意思や権利を尊重し、地域で安心して暮らし続けられることを目指しています。\n\nあなたは、どのような立場や関心から、この計画に意見を伝えたいですか？\n\nご自身の暮らし、家族や身近な人への支援、仕事や地域活動、将来の自分や家族への関心など、話せる範囲で教えてください。",
      "素案には、本人の発信や地域参加、学校や店舗などでの認知症への理解、早めの相談や生活上の備え、本人の意思を尊重する支援、医療・介護との連携、家族への支援などが盛り込まれています。若年性認知症の仕事や子育てへの相談支援も含まれます。\n\nこの中で、特に大切だと思うことや、気になっていることは何ですか？\n\nここに挙げていないことでも構いません。",
      "いま挙げていただいた点について、日々の暮らしや支援の場面で、助けになったこと、困ったこと、不安に感じていることはありますか？\n\n例えば、相談先につながるまでのこと、買い物や外出での周囲の対応、本人の希望が支援に反映されたかどうかなど、話せる範囲で教えてください。経験がなければ、『こうなってほしい』という期待でも構いません。",
      "区は、本人による発信や社会参加を取組の中心に置き、周囲の理解を広げる取組と、相談・医療・介護・地域づくりをつなげて暮らしを支える方針です。\n\nこの計画の目的や内容について、あなたの経験や関心に照らして、納得できる点と、まだ不十分・分かりにくいと感じる点はありますか？\n\nどちらか一方についてでも構いません。",
      "素案には、講座や交流会の参加人数、本人が地域活動に参画している地区の割合、区民の認知症への考え方などの評価項目があり、数値目標は調整中です。\n\nあなたが気にしている取組について、本人や家族の暮らしにどのような変化があれば、『支援が役立っている』と感じますか？\n\nまた、その変化を区が確かめるには、誰の声や、どのような情報を集めるとよいと思いますか？",
      "ここまでのお話を踏まえて、計画に追加・修正してほしいことや、実際の支援の進め方で変えてほしいことは何ですか？\n\n相談窓口の案内、診断後の支援へのつなぎ方、本人の希望の確かめ方、家族への支援など、関心のある点について、『誰に、どのような場面で、どのような対応があるとよいか』を教えてください。いまある取組で、続けてほしいことや広げてほしいことでも構いません。",
      "ここまでのお話を踏まえて、認知症になってからの暮らしを支えるこの計画について、区に最も伝えたいことを一文で表すと、どのような言葉になりますか？\n\n大切にしてほしいこと、変えてほしいこと、続けてほしいことの、いずれでも構いません。",
    ]);
  });

  it("診断の有無を明かさなくても選べる最初の回答候補を用意する", () => {
    expect(DEMENTIA_HOPE_PLAN_QUESTIONS[0].quickReplies).toEqual([
      "自分の暮らしや将来への関心から",
      "家族や身近な人への支援から",
      "仕事や地域活動から",
      "制度や地域社会への関心から",
    ]);
  });
});
